"""Regenerate deployment/k8s/kustomization.yaml from hermes-profile/ (run after adding/removing skills or scripts).

ConfigMaps cannot hold directories, so files are flattened: skills/<n>/SKILL.md -> skills__<n>__SKILL.md,
scripts/<f> -> scripts__<f>. profile-init.sh (init container) unflattens them into HERMES_HOME.
Usage: python3 deployment/k8s/gen_kustomization.py [--check]
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROFILE = HERE.parents[1] / "hermes-profile"
OUT = HERE / "kustomization.yaml"


def render() -> str:
    files = ["SOUL.md=../../hermes-profile/SOUL.md", "profile-init.sh=profile-init.sh"]
    for p in sorted(PROFILE.glob("skills/*/SKILL.md")):
        files.append(f"skills__{p.parent.name}__SKILL.md=../../hermes-profile/skills/{p.parent.name}/SKILL.md")
    for p in sorted(PROFILE.glob("scripts/*.py")):
        files.append(f"scripts__{p.name}=../../hermes-profile/scripts/{p.name}")
    lines = "\n".join(f"      - {f}" for f in files)
    return f"""# REQUIRES FROM NIR: C1 (docs/OPEN-QUESTIONS.md). Before implementing/filling run `python3 scripts/open_items.py --file deployment/k8s/kustomization.yaml`; if BLOCKED, ask Nir. Never invent.
# GENERATED by gen_kustomization.py - do not edit by hand. VERIFY the namespace.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: TBD-noc-engineer
resources:
  - hermes.yaml
  - noc-mcp.yaml
configMapGenerator:
  - name: hermes-profile
    files:
{lines}
  - name: noc-mcp-config
    files:
      - backends.yaml=../../noc-mcp/config/backends.example.yaml   # TBD: point at the real (private) backends.yaml
      - pipeline.yaml=../../noc-mcp/config/pipeline.yaml
      - rule-paths.yaml=../../noc-mcp/config/rule-paths.example.yaml
"""


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text() == text else "kustomization.yaml is stale: run gen_kustomization.py")
    OUT.write_text(text)
    print(f"wrote {OUT} ({text.count('      - ')} files)")
